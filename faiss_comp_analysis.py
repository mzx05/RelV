class LLMAnswerGrader:
    def __init__(self, llm):
        """Initialize grader with LLM for evaluation"""
        self.llm = llm
        self.grading_prompt_template = """You are an expert evaluator assessing the quality of answers to questions about a merger document.

Question: {question}
Expected Answer: {expected_answer}
Actual Answer: {actual_answer}

Grading criteria:
1. Correctness: Is the information in the actual answer factually correct according to the expected answer?
2. Completeness: Does the actual answer cover all important points from the expected answer?
3. Relevance: Does the actual answer directly address the question being asked?
4. Precision: Is the actual answer concise and to the point without unnecessary information?

Please consider these criteria and provide:
1. A score between 0.0 and 1.0, where:
   - 0.0-0.2: Completely incorrect or irrelevant
   - 0.2-0.4: Mostly incorrect with minor valid points
   - 0.4-0.6: Partially correct but missing key information
   - 0.6-0.8: Mostly correct with minor issues
   - 0.8-1.0: Completely correct and comprehensive

2. A brief explanation of your grading (1-2 sentences)

FORMAT YOUR RESPONSE EXACTLY LIKE THIS:
Score: [number between 0 and 1]
Explanation: [brief explanation]"""

    def grade_single_answer_simple(self, question: str, expected: str, actual: str) -> Dict[str, Any]:
        """Simplified grading with more flexible prompt"""

        # Handle empty or error answers
        if not actual or actual.strip() in ["", "No relevant context found", "Error: Context too long for model"]:
            return {
                'score': 0.0,
                'explanation': "No valid answer provided",
                'raw_response': "N/A - Empty answer"
            }

        # Simplified prompt that's more likely to get proper format
        simple_prompt = f"""Grade this answer on a scale of 0.0 to 1.0:

Question: {question}
Expected: {expected}
Actual: {actual}

Give a score from 0.0 (completely wrong) to 1.0 (perfect) and explain why.

Score: """

        try:
            response = self.llm(simple_prompt, max_tokens=150, temperature=0.1, stop=["\n"])
            raw_response = response['choices'][0]['text'].strip()

            # Try to extract just a number first
            number_match = re.search(r'([0-9]*\.?[0-9]+)', raw_response)
            if number_match:
                score = float(number_match.group(1))
                score = max(0.0, min(1.0, score))

                # Get explanation by prompting again
                explain_prompt = f"""Why did you give this answer a score of {score}?

Question: {question}
Expected: {expected}
Actual: {actual}

Brief explanation: """

                explain_response = self.llm(explain_prompt, max_tokens=100, temperature=0.1)
                explanation = explain_response['choices'][0]['text'].strip()

            else:
                score = 0.0
                explanation = f"Could not parse score from: {raw_response}"

            return {
                'score': score,
                'explanation': explanation,
                'raw_response': raw_response
            }

        except Exception as e:
            print(f"Error in simple grading: {e}")
            return {
                'score': 0.0,
                'explanation': f"Grading error: {str(e)}",
                'raw_response': "Error"
            }
        """Grade a single answer using LLM evaluation"""

        # Handle empty or error answers
        if not actual or actual.strip() in ["", "No relevant context found", "Error: Context too long for model"]:
            return {
                'score': 0.0,
                'explanation': "No valid answer provided",
                'raw_response': "N/A - Empty answer"
            }

        # Create grading prompt
        prompt = self.grading_prompt_template.format(
            question=question,
            expected_answer=expected,
            actual_answer=actual
        )

        try:
            # Get LLM evaluation with more specific parameters
            response = self.llm(
                prompt,
                max_tokens=250,  # Increased for full response
                temperature=0.1,
                stop=["\n\nQuestion:", "\n\n\n"]  # Better stop tokens
            )
            raw_response = response['choices'][0]['text'].strip()

            # Parse score and explanation
            score, explanation = self.parse_grading_response(raw_response)

            return {
                'score': score,
                'explanation': explanation,
                'raw_response': raw_response
            }

        except Exception as e:
            print(f"Error grading answer: {e}")
            return {
                'score': 0.0,
                'explanation': f"Error during grading: {str(e)}",
                'raw_response': "Error"
            }

    def parse_grading_response(self, response: str) -> Tuple[float, str]:
        """Parse the LLM grading response to extract score and explanation"""
        try:
            print(f"Debug - Raw response: '{response}'")  # Debug output

            # Try multiple parsing strategies
            score = 0.0
            explanation = "Could not parse response"

            # Strategy 1: Look for "Score:" pattern
            score_match = re.search(r'Score:\s*([0-9]*\.?[0-9]+)', response, re.IGNORECASE)
            if score_match:
                score = float(score_match.group(1))
                score = max(0.0, min(1.0, score))  # Clamp to valid range
            else:
                # Strategy 2: Look for any decimal number (fallback)
                number_match = re.search(r'([0-9]*\.?[0-9]+)', response)
                if number_match:
                    potential_score = float(number_match.group(1))
                    if 0.0 <= potential_score <= 1.0:
                        score = potential_score

            # Strategy 1: Look for "Explanation:" pattern
            explanation_match = re.search(r'Explanation:\s*(.+)', response, re.IGNORECASE | re.DOTALL)
            if explanation_match:
                explanation = explanation_match.group(1).strip()
            else:
                # Strategy 2: Look for text after score (fallback)
                if score_match:
                    # Get everything after the score line
                    score_end = score_match.end()
                    remaining_text = response[score_end:].strip()
                    if remaining_text:
                        # Remove any remaining "Explanation:" prefix
                        remaining_text = re.sub(r'^Explanation:\s*', '', remaining_text, flags=re.IGNORECASE)
                        explanation = remaining_text
                else:
                    # Strategy 3: Use the whole response as explanation if no score found
                    explanation = response.strip()

            # Clean up explanation
            explanation = explanation.replace('\n', ' ').strip()
            if len(explanation) > 200:  # Truncate very long explanations
                explanation = explanation[:200] + "..."

            return score, explanation

        except Exception as e:
            print(f"Error parsing grading response: {e}")
            return 0.0, f"Parse error: {str(e)}"

    def grade_experiment_results(self, results_file: str, experiment_name: str) -> Dict[str, Any]:
        """Grade all answers in an experiment results file"""
        print(f"\n{'='*60}")
        print(f"GRADING {experiment_name}")
        print(f"{'='*60}")

        # Load results
        try:
            with open(results_file, 'r', encoding='utf-8') as f:
                experiment_data = json.load(f)
        except Exception as e:
            print(f"Error loading results file {results_file}: {e}")
            return None

        results = experiment_data['results']
        graded_results = []

        print(f"Grading {len(results)} answers...")

        for i, result in enumerate(results):
            print(f"Grading answer {i+1}/{len(results)}...")

            question = result['question']
            expected = result['expected_answer']
            actual = result['generated_answer']

            # Grade the answer - try main method first, then fallback to simple
            grading = self.grade_single_answer_simple(question, expected, actual)

            # If parsing failed, try simple method
            if grading['explanation'] == "Could not parse explanation from response":
                print(f"  Retrying with simple grading method...")
                grading = self.grade_single_answer_simple(question, expected, actual)

            # Show debug info for first few answers
            if i < 3:  # Debug first 3 answers
                print(f"  Question: {question[:50]}...")
                print(f"  Raw LLM response: {grading['raw_response']}")
                print(f"  Parsed score: {grading['score']}")
                print(f"  Parsed explanation: {grading['explanation'][:100]}...")

            # Combine original result with grading
            graded_result = {
                **result,  # Original data
                'llm_score': grading['score'],
                'llm_explanation': grading['explanation'],
                'llm_raw_response': grading['raw_response']
            }

            graded_results.append(graded_result)

        # Calculate grading statistics
        scores = [r['llm_score'] for r in graded_results]
        grading_stats = {
            'total_answers': len(scores),
            'avg_score': np.mean(scores),
            'median_score': np.median(scores),
            'std_score': np.std(scores),
            'min_score': np.min(scores),
            'max_score': np.max(scores),
            'score_distribution': self.get_score_distribution(scores)
        }

        return {
            'experiment_name': experiment_name,
            'graded_results': graded_results,
            'original_metrics': experiment_data['metrics'],
            'grading_stats': grading_stats
        }

    def get_score_distribution(self, scores: List[float]) -> Dict[str, int]:
        """Calculate distribution of scores by grade bands"""
        distribution = {
            '0.0-0.2 (Poor)': 0,
            '0.2-0.4 (Below Average)': 0,
            '0.4-0.6 (Average)': 0,
            '0.6-0.8 (Good)': 0,
            '0.8-1.0 (Excellent)': 0
        }

        for score in scores:
            if score <= 0.2:
                distribution['0.0-0.2 (Poor)'] += 1
            elif score <= 0.4:
                distribution['0.2-0.4 (Below Average)'] += 1
            elif score <= 0.6:
                distribution['0.4-0.6 (Average)'] += 1
            elif score <= 0.8:
                distribution['0.6-0.8 (Good)'] += 1
            else:
                distribution['0.8-1.0 (Excellent)'] += 1

        return distribution

