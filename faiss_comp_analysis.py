# Document Processing and Chunking
class DocumentProcessor:
    def __init__(self, chunk_size: int = 512, overlap: int = 50):
        self.chunk_size = chunk_size
        self.overlap = overlap

    def extract_text_from_pdf(self, pdf_path: str) -> str:
        """Extract text from PDF file using PyMuPDF"""
        print(f"Extracting text from PDF: {pdf_path}")

        if not os.path.exists(pdf_path):
            raise FileNotFoundError(f"PDF file not found: {pdf_path}")

        text = ""
        try:
            doc = fitz.open(pdf_path)
            print(f"PDF has {len(doc)} pages")

            for page_num in range(len(doc)):
                page = doc.load_page(page_num)
                page_text = page.get_text()
                text += page_text + "\n"

                if (page_num + 1) % 10 == 0:
                    print(f"Processed {page_num + 1} pages...")

            doc.close()
            print(f"Successfully extracted {len(text)} characters from PDF")

        except Exception as e:
            raise Exception(f"Error extracting text from PDF: {str(e)}")

        return text

    def clean_text(self, text: str) -> str:
        """Clean and normalize text"""
        # Remove excessive whitespace and newlines
        text = re.sub(r'\n+', ' ', text)
        text = re.sub(r'\s+', ' ', text)
        return text.strip()

    def chunk_text(self, text: str) -> List[Dict[str, Any]]:
        """Split text into overlapping chunks"""
        cleaned_text = self.clean_text(text)
        words = cleaned_text.split()

        chunks = []
        start_idx = 0
        chunk_id = 0

        while start_idx < len(words):
            end_idx = min(start_idx + self.chunk_size, len(words))
            chunk_text = ' '.join(words[start_idx:end_idx])

            chunks.append({
                'id': chunk_id,
                'text': chunk_text,
                'start_word': start_idx,
                'end_word': end_idx,
                'char_start': len(' '.join(words[:start_idx])),
                'char_end': len(' '.join(words[:end_idx]))
            })

            chunk_id += 1
            start_idx = end_idx - self.overlap

            if end_idx >= len(words):
                break

        return chunks

# FAISS Vector Store
class FAISSVectorStore:
    def __init__(self, embedding_model_name: str = "all-MiniLM-L6-v2"):
        print(f"Loading embedding model: {embedding_model_name}")
        self.embedding_model = SentenceTransformer(embedding_model_name)
        self.dimension = self.embedding_model.get_sentence_embedding_dimension()
        self.index = None
        self.chunks = []
        self.embeddings = None

    def create_embeddings(self, chunks: List[Dict[str, Any]]) -> np.ndarray:
        """Create embeddings for text chunks"""
        texts = [chunk['text'] for chunk in chunks]
        print(f"Creating embeddings for {len(texts)} chunks...")

        # Create embeddings in batches to avoid memory issues
        batch_size = 32
        embeddings = []

        for i in range(0, len(texts), batch_size):
            batch_texts = texts[i:i + batch_size]
            batch_embeddings = self.embedding_model.encode(batch_texts, show_progress_bar=True)
            embeddings.append(batch_embeddings)

        return np.vstack(embeddings)

    def build_index(self, chunks: List[Dict[str, Any]]):
        """Build FAISS index from chunks"""
        self.chunks = chunks
        self.embeddings = self.create_embeddings(chunks)

        # Create FAISS index
        print("Building FAISS index...")
        self.index = faiss.IndexFlatIP(self.dimension)  # Inner product for cosine similarity

        # Normalize embeddings for cosine similarity
        faiss.normalize_L2(self.embeddings)
        self.index.add(self.embeddings)

        print(f"FAISS index built with {self.index.ntotal} vectors")

    def search(self, query: str, k: int = 5) -> List[Dict[str, Any]]:
        """Search for similar chunks"""
        if self.index is None:
            raise ValueError("Index not built. Call build_index first.")

        # Encode query
        query_embedding = self.embedding_model.encode([query])
        faiss.normalize_L2(query_embedding)

        # Search
        scores, indices = self.index.search(query_embedding, k)

        results = []
        for i, (score, idx) in enumerate(zip(scores[0], indices[0])):
            if idx != -1:  # Valid result
                results.append({
                    'chunk': self.chunks[idx],
                    'score': float(score),
                    'rank': i + 1
                })

        return results

# Evaluation Framework
class FAISSEvaluator:
    def __init__(self, vector_store: FAISSVectorStore, llm, max_context_tokens: int = 1500):
        self.vector_store = vector_store
        self.llm = llm
        self.max_context_tokens = max_context_tokens  # Leave room for prompt and response

    def estimate_tokens(self, text: str) -> int:
        """Rough token estimation (1 token ≈ 4 characters)"""
        return len(text) // 4

    def truncate_context(self, context: str, max_tokens: int) -> str:
        """Truncate context to fit within token limits"""
        estimated_tokens = self.estimate_tokens(context)

        if estimated_tokens <= max_tokens:
            return context

        # Truncate to approximately the right number of characters
        max_chars = max_tokens * 4
        if len(context) > max_chars:
            # Try to truncate at sentence boundaries
            truncated = context[:max_chars]
            last_period = truncated.rfind('.')
            last_newline = truncated.rfind('\n')

            # Cut at the latest sentence or paragraph boundary
            cut_point = max(last_period, last_newline)
            if cut_point > max_chars * 0.7:  # Only if we don't lose too much
                truncated = truncated[:cut_point + 1]

            return truncated + "..."

        return context

    def generate_answer(self, question: str, context: str) -> str:
        """Generate answer using LLM with retrieved context"""
        # Truncate context to fit within token limits
        truncated_context = self.truncate_context(context, self.max_context_tokens)

        prompt = f"""Based on the following context, answer the question concisely and accurately.

Context: {truncated_context}

Question: {question}

Answer:"""

        # Double-check prompt length
        prompt_tokens = self.estimate_tokens(prompt)
        if prompt_tokens > 1800:  # Leave room for response
            # Further truncate context if needed
            available_for_context = self.max_context_tokens - 300  # Reduce further
            truncated_context = self.truncate_context(context, available_for_context)

            prompt = f"""Based on the following context, answer the question concisely.

Context: {truncated_context}

Question: {question}

Answer:"""

        try:
            response = self.llm(prompt, max_tokens=150, temperature=0.1, stop=["\n\n", "\n"])
            return response['choices'][0]['text'].strip()
        except Exception as e:
            print(f"Error generating answer: {e}")
            print(f"Prompt length (estimated): {self.estimate_tokens(prompt)} tokens")
            return "Error: Context too long for model"

    def evaluate_question(self, question_data: Dict[str, Any], top_k: int = 3) -> Dict[str, Any]:
        """Evaluate a single question"""
        question = question_data['question']
        expected_answer = question_data.get('answer', question_data.get('expected_answer', ''))

        # Search for relevant chunks
        search_results = self.vector_store.search(question, k=top_k)

        if not search_results:
            return {
                'question': question,
                'expected_answer': expected_answer,
                'generated_answer': 'No relevant context found',
                'search_results': [],
                'top_score': 0.0,
                'context_used': '',
                'context_truncated': False
            }

        # Combine top results as context, but be smarter about length
        context_parts = []
        total_estimated_tokens = 0
        context_truncated = False

        for result in search_results:
            chunk_text = result['chunk']['text']
            chunk_tokens = self.estimate_tokens(chunk_text)

            # Stop adding chunks if we're getting close to limit
            if total_estimated_tokens + chunk_tokens > self.max_context_tokens:
                context_truncated = True
                break

            context_parts.append(f"[Score: {result['score']:.3f}] {chunk_text}")
            total_estimated_tokens += chunk_tokens

        # If no chunks fit, use just the top one but truncated
        if not context_parts and search_results:
            top_chunk = search_results[0]['chunk']['text']
            truncated_chunk = self.truncate_context(top_chunk, self.max_context_tokens)
            context_parts = [f"[Score: {search_results[0]['score']:.3f}] {truncated_chunk}"]
            context_truncated = True

        combined_context = "\n\n".join(context_parts)

        # Generate answer
        generated_answer = self.generate_answer(question, combined_context)

        return {
            'question': question,
            'expected_answer': expected_answer,
            'generated_answer': generated_answer,
            'search_results': search_results,
            'top_score': search_results[0]['score'] if search_results else 0.0,
            'context_used': combined_context,
            'context_truncated': context_truncated,
            'num_chunks_used': len(context_parts),
            'estimated_tokens': self.estimate_tokens(combined_context)
        }

    def evaluate_dataset(self, dataset: List[Dict[str, Any]], top_k: int = 3) -> Dict[str, Any]:
        """Evaluate entire dataset"""
        print(f"Evaluating {len(dataset)} questions...")

        results = []
        for i, question_data in enumerate(dataset):
            print(f"Processing question {i+1}/{len(dataset)}")
            result = self.evaluate_question(question_data, top_k)
            results.append(result)

        # Calculate metrics
        avg_top_score = np.mean([r['top_score'] for r in results])
        truncated_count = sum(1 for r in results if r.get('context_truncated', False))
        avg_tokens_used = np.mean([r.get('estimated_tokens', 0) for r in results])

        return {
            'results': results,
            'metrics': {
                'avg_top_score': avg_top_score,
                'total_questions': len(results),
                'context_truncated_count': truncated_count,
                'avg_tokens_used': avg_tokens_used
            }
        }

# Main Experiment Runner
class ExperimentRunner:
    def __init__(self, llm, chunk_size: int = 256, overlap: int = 32):  # Smaller chunks
        self.llm = llm
        self.processor = DocumentProcessor(chunk_size=chunk_size, overlap=overlap)
        self.vector_store = FAISSVectorStore()

    def load_dataset(self, json_path: str) -> List[Dict[str, Any]]:
        """Load dataset from JSON file"""
        print(f"Loading dataset from: {json_path}")

        if not os.path.exists(json_path):
            raise FileNotFoundError(f"JSON file not found: {json_path}")

        try:
            with open(json_path, 'r', encoding='utf-8') as file:
                data = json.load(file)

            print(f"Successfully loaded {len(data)} questions from {json_path}")
            return data

        except Exception as e:
            raise Exception(f"Error loading JSON file {json_path}: {str(e)}")

    def prepare_document_from_pdf(self, pdf_path: str):
        """Process PDF document and index it"""
        print("Extracting text from PDF...")
        document_text = self.processor.extract_text_from_pdf(pdf_path)

        print("Processing document...")
        chunks = self.processor.chunk_text(document_text)
        print(f"Created {len(chunks)} chunks")

        print("Building FAISS index...")
        self.vector_store.build_index(chunks)

        return document_text

    def prepare_document(self, document_text: str):
        """Process and index document text"""
        print("Processing document...")
        chunks = self.processor.chunk_text(document_text)
        print(f"Created {len(chunks)} chunks")

        print("Building FAISS index...")
        self.vector_store.build_index(chunks)

    def run_experiment(self, dataset: List[Dict[str, Any]], experiment_name: str, top_k: int = 3):
        """Run complete experiment"""
        print(f"\n{'='*50}")
        print(f"Running {experiment_name}")
        print(f"{'='*50}")

        evaluator = FAISSEvaluator(self.vector_store, self.llm)
        results = evaluator.evaluate_dataset(dataset, top_k)

        # Display results
        self.display_results(results, experiment_name)

        return results

    def display_results(self, results: Dict[str, Any], experiment_name: str):
        """Display experiment results"""
        metrics = results['metrics']
        print(f"\n{experiment_name} Results:")
        print(f"Average Top Score: {metrics['avg_top_score']:.4f}")
        print(f"Total Questions: {metrics['total_questions']}")
        print(f"Context Truncated: {metrics['context_truncated_count']}/{metrics['total_questions']} questions")
        print(f"Average Tokens Used: {metrics['avg_tokens_used']:.0f}")

        print("\nSample Results:")
        for i, result in enumerate(results['results'][:3]):  # Show first 3
            print(f"\n--- Question {i+1} ---")
            print(f"Q: {result['question']}")
            print(f"Expected: {result['expected_answer']}")
            print(f"Generated: {result['generated_answer']}")
            print(f"Top Score: {result['top_score']:.4f}")
            print(f"Tokens Used: {result.get('estimated_tokens', 0)}")
            if result.get('context_truncated', False):
                print("⚠️  Context was truncated due to length")

